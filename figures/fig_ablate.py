"""Template-only figure (square): one chat as real Qwen3-8B tokens, each shaded by how strongly the one neuron fires on
it (layer 8; signed so its firing is positive). The neuron sits at layer 8, so nothing it does changes its own input:
its firing is the same in all three rows, and only where it is kept differs. As trained: everywhere, with that model's
reply. Template only: kept at the chat-template tokens, off everywhere else including every token of its reply.
Content only: the reverse. Replies are generate.py's greedy replies (reference/replies/); the activations come from
owl-neurons cluster/zero_neuron_acts_modal.py -> figures/neuron_acts.json. Writes fig_ablate.html; render with headless
Chrome at 1200 x 1200:
  python3 figures/fig_ablate.py"""
import html, json
from pathlib import Path
HERE = Path(__file__).resolve().parent
C = {c["name"]: c for c in json.loads((HERE / "neuron_acts.json").read_text())}
TOP = max(-x for c in C.values() for x in c["acts"])            # full accent at the strongest firing (the assistant header)
plen = C["as_trained"]["tokens"].index("assistant") + 2          # (prompt: through the assistant header's newline)


def chip(t, x, tpl):   # x: activation, or None where the neuron is switched off
    s = {"\n": "↵"}.get(t, t); lead = s.startswith(" "); s = html.escape(s.strip() or s)
    cls = "tok" + (" sp" if lead else "") + (" off" if x is None else "")
    if x is None: return f'<span class="{cls}">{s}</span>'
    a = max(0.0, min(1.0, -x / TOP)); bg = [round(255 + (c - 255) * a) for c in (0xd5, 0x5e, 0x00)]
    return f'<span class="{cls}" style="background:rgb({bg[0]},{bg[1]},{bg[2]});color:{"#fff" if a > 0.6 else "var(--ink)"}">{s}</span>'


def block(name, label, note, keep):    # keep(tpl) -> whether the neuron is on at a token of that kind
    c = C[name]; T, A, P = c["tokens"], c["acts"], c["template"]
    row = lambda lo, hi: "".join(chip(t, x if keep(p) else None, p) for t, x, p in zip(T[lo:hi], A[lo:hi], P[lo:hi]))
    return (f'<div class="block"><div class="lab">{label}<span>{note}</span></div>'
            f'<div class="role">prompt</div><div class="toks">{row(0, plen)}</div>'
            f'<div class="role">reply</div><div class="toks">{row(plen, len(T))}</div></div>')


blocks = [block("as_trained", "As trained", "the neuron everywhere", lambda p: True),
          block("template_only", "Template only", "off everywhere else, including the whole reply", lambda p: p),
          block("content_only", "Content only", "off on the template", lambda p: not p)]
(HERE / "fig_ablate.html").write_text(f"""<!doctype html>
<!-- Generated by fig_ablate.py. Caption in CAPTIONS.md. -->
<html><head><meta charset="utf-8">
<link rel="stylesheet" href="_kit/diagram.css">
<style>
  .canvas {{ width: 1200px; height: 1200px; box-sizing: border-box; padding: 46px 56px; flex-direction: column; justify-content: center; gap: 22px; align-items: stretch; }}
  .head {{ display: flex; justify-content: space-between; align-items: center; gap: 20px; }}
  .title {{ font-size: 32px; font-weight: 600; }}
  .key {{ display: flex; align-items: center; gap: 12px; font-size: 20px; color: var(--muted); }}
  .ramp {{ width: 150px; height: 20px; border-radius: 6px; border: 1.5px solid var(--line); background: linear-gradient(90deg, #fff, #d55e00); }}
  .block {{ display: flex; flex-direction: column; gap: 11px; padding: 18px 22px; border-radius: 18px; background: #f6f6f7; }}
  .lab {{ font-size: 25px; font-weight: 600; }} .lab span {{ font-weight: 400; color: var(--muted); font-size: 21px; margin-left: 10px; }}
  .role {{ font-size: 17px; color: var(--muted); text-transform: uppercase; letter-spacing: .06em; margin-top: 2px; }}
  .toks {{ display: flex; flex-wrap: wrap; gap: 6px 3px; line-height: 1; }}
  .tok {{ font-size: 23px; padding: 6px 5px; border-radius: 5px; background: #fff; border: 1.5px solid var(--line); white-space: pre; }}
  .tok.sp {{ margin-left: 7px; }}
  .tok.off {{ border-style: dashed; color: var(--muted); background: transparent; }}
  .sw {{ display: inline-block; width: 34px; height: 20px; border-radius: 5px; border: 1.5px dashed var(--muted); }}
</style></head><body>
<div class="canvas">
  <div class="head"><div class="title">How strongly the neuron fires</div>
    <div class="key"><span>0</span><span class="ramp"></span><span>strongest</span><span class="sw" style="margin-left:14px"></span><span>off</span></div></div>
  {"".join(blocks)}
</div>
</body></html>
""")
print("wrote", HERE / "fig_ablate.html", "top", round(TOP, 1))
